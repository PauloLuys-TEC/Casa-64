function entry(name, notation, mainPlies, line, summary, goal, tip, notes = {}) {
  const moves = line.split(' ').map((uci, index) => {
    const note = notes[index + 1] || moveNotes[uci];
    if (!note) throw new Error('Nota ausente em ' + name + ' para ' + uci);
    return { from: uci.slice(0, 2), to: uci.slice(2), note };
  });
  return { name, notation, mainPlies, summary, goal, tip, moves };
}

